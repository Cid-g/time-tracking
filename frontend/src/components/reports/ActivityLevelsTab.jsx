import { useState, useEffect, useCallback } from 'react';
import useReports from '../../hooks/useReports';

const getDefaultDateRange = () => {
  const now = new Date();
  const start = new Date(now.getFullYear(), now.getMonth(), 1);
  return {
    startDate: start.toISOString().split('T')[0],
    endDate: now.toISOString().split('T')[0],
  };
};

const DAY_LABELS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const DIST_COLORS = {
  'Idle (0-20%)': { bg: 'bg-red-500/15', bar: 'from-red-500/60 to-red-400/40', text: 'text-red-400' },
  'Low (20-50%)': { bg: 'bg-amber-500/15', bar: 'from-amber-500/60 to-amber-400/40', text: 'text-amber-400' },
  'Medium (50-75%)': { bg: 'bg-cyan-500/15', bar: 'from-cyan-500/60 to-cyan-400/40', text: 'text-cyan-400' },
  'High (75-100%)': { bg: 'bg-emerald-500/15', bar: 'from-emerald-500/60 to-emerald-400/40', text: 'text-emerald-400' },
};

const getHeatmapColor = (value) => {
  if (value === 0) return 'bg-white/[0.03]';
  if (value < 20) return 'bg-red-500/30';
  if (value < 40) return 'bg-amber-500/25';
  if (value < 60) return 'bg-cyan-500/20';
  if (value < 80) return 'bg-emerald-500/30';
  return 'bg-emerald-500/50';
};

const ActivityLevelsTab = () => {
  const { activityLevels, activityLoading, loadActivityLevels, heatmapData, heatmapLoading, loadHeatmap } = useReports();

  const [dateRange, setDateRange] = useState(getDefaultDateRange);

  const loadData = useCallback(() => {
    const params = { startDate: dateRange.startDate, endDate: dateRange.endDate };
    loadActivityLevels(params);
    loadHeatmap(params);
  }, [dateRange, loadActivityLevels, loadHeatmap]);

  useEffect(() => {
    loadData();
  }, [loadData]);

  const summary = activityLevels?.summary;
  const users = activityLevels?.users || [];
  const distribution = activityLevels?.distribution || [];
  const dailyTrend = activityLevels?.dailyTrend || [];
  const grid = heatmapData?.grid || [];

  const maxDistCount = distribution.length > 0 ? Math.max(...distribution.map((d) => d.count)) : 1;
  const maxDailyAvg = dailyTrend.length > 0 ? Math.max(...dailyTrend.map((d) => d.avgOverall)) : 1;
  const loading = activityLoading || heatmapLoading;

  return (
    <div className="space-y-6">
      {/* Controls */}
      <div className="flex flex-wrap items-center gap-3">
        <div className="flex items-center gap-2 bg-white/[0.04] border border-white/[0.08] rounded-xl px-3 py-2">
          <label className="text-[12px] text-white/35 font-medium">From</label>
          <input
            type="date"
            value={dateRange.startDate}
            onChange={(e) => setDateRange((prev) => ({ ...prev, startDate: e.target.value }))}
            className="bg-transparent text-[13px] text-white border-none outline-none cursor-pointer"
          />
        </div>
        <div className="flex items-center gap-2 bg-white/[0.04] border border-white/[0.08] rounded-xl px-3 py-2">
          <label className="text-[12px] text-white/35 font-medium">To</label>
          <input
            type="date"
            value={dateRange.endDate}
            onChange={(e) => setDateRange((prev) => ({ ...prev, endDate: e.target.value }))}
            className="bg-transparent text-[13px] text-white border-none outline-none cursor-pointer"
          />
        </div>
      </div>

      {loading ? (
        <div className="space-y-4">
          {[...Array(4)].map((_, i) => (
            <div key={i} className="bg-white/[0.04] rounded-xl h-20 animate-pulse" />
          ))}
        </div>
      ) : !activityLevels ? (
        <div className="flex flex-col items-center justify-center py-16 text-white/30">
          <svg width="40" height="40" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.5" className="mb-3 opacity-40">
            <polyline points="22 12 18 12 15 21 9 3 6 12 2 12"/>
          </svg>
          <p className="text-[14px] font-medium">No activity data available</p>
          <p className="text-[12px] text-white/20 mt-1">Activity logs are generated by the desktop agent</p>
        </div>
      ) : (
        <>
          {/* Summary Cards */}
          <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
            {[
              { label: 'Avg Activity', value: `${summary?.avgOverallActivity || 0}%`, color: 'cyan' },
              { label: 'Users Tracked', value: summary?.usersTracked || 0, color: 'purple' },
              { label: 'Total Intervals', value: (summary?.totalIntervals || 0).toLocaleString(), color: 'emerald' },
            ].map((card) => (
              <div key={card.label} className="bg-white/[0.04] rounded-xl border border-white/[0.06] p-4 text-center">
                <p className="text-[11px] text-white/30 font-medium mb-1">{card.label}</p>
                <p className={`text-[20px] font-bold text-${card.color}-400`}>{card.value}</p>
              </div>
            ))}
          </div>

          {/* Activity Distribution */}
          {distribution.length > 0 && (
            <div className="bg-white/[0.03] rounded-2xl border border-white/[0.06] p-5">
              <h3 className="text-[14px] font-semibold text-white mb-4">Activity Distribution</h3>
              <div className="space-y-3">
                {distribution.map((d) => {
                  const pct = maxDistCount > 0 ? (d.count / maxDistCount) * 100 : 0;
                  const colors = DIST_COLORS[d.label] || DIST_COLORS['Medium (50-75%)'];
                  return (
                    <div key={d.label}>
                      <div className="flex items-center justify-between mb-1">
                        <span className={`text-[13px] font-medium ${colors.text}`}>{d.label}</span>
                        <div className="flex items-center gap-2">
                          <span className="text-[12px] text-white/50">{d.count} intervals</span>
                          <span className="text-[11px] text-white/25">avg {d.avgActivity}%</span>
                        </div>
                      </div>
                      <div className="h-2 bg-white/[0.06] rounded-full overflow-hidden">
                        <div
                          className={`h-full bg-gradient-to-r ${colors.bar} rounded-full transition-all duration-500`}
                          style={{ width: `${pct}%` }}
                        />
                      </div>
                    </div>
                  );
                })}
              </div>
            </div>
          )}

          {/* Heatmap */}
          {grid.length > 0 && (
            <div className="bg-white/[0.03] rounded-2xl border border-white/[0.06] p-5">
              <h3 className="text-[14px] font-semibold text-white mb-4">Activity Heatmap</h3>
              <div className="overflow-x-auto">
                {/* Hour labels */}
                <div className="flex mb-1 pl-10">
                  {Array.from({ length: 24 }, (_, h) => (
                    <div key={h} className="flex-1 text-center text-[9px] text-white/20 font-mono min-w-[20px]">
                      {h}
                    </div>
                  ))}
                </div>
                {/* Grid rows */}
                {grid.map((row, dayIdx) => (
                  <div key={dayIdx} className="flex items-center gap-1 mb-1">
                    <span className="text-[10px] text-white/30 font-medium w-8 text-right shrink-0">{DAY_LABELS[dayIdx]}</span>
                    <div className="flex flex-1 gap-[2px]">
                      {row.map((val, hourIdx) => (
                        <div
                          key={hourIdx}
                          className={`flex-1 min-w-[20px] h-5 rounded-sm ${getHeatmapColor(val)} transition-colors group relative`}
                          title={`${DAY_LABELS[dayIdx]} ${hourIdx}:00 - ${val}%`}
                        >
                          <div className="absolute bottom-full left-1/2 -translate-x-1/2 mb-1 px-1.5 py-0.5 bg-black/80 rounded text-[9px] text-white font-mono opacity-0 group-hover:opacity-100 transition-opacity pointer-events-none whitespace-nowrap z-10">
                            {val}%
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                ))}
                {/* Legend */}
                <div className="flex items-center gap-2 mt-3 pl-10">
                  <span className="text-[10px] text-white/20">Low</span>
                  <div className="flex gap-[2px]">
                    {['bg-white/[0.03]', 'bg-red-500/30', 'bg-amber-500/25', 'bg-cyan-500/20', 'bg-emerald-500/30', 'bg-emerald-500/50'].map((c, i) => (
                      <div key={i} className={`w-4 h-3 rounded-sm ${c}`} />
                    ))}
                  </div>
                  <span className="text-[10px] text-white/20">High</span>
                </div>
              </div>
            </div>
          )}

          {/* Per-User Breakdown */}
          {users.length > 0 && (
            <div className="bg-white/[0.03] rounded-2xl border border-white/[0.06] p-5">
              <h3 className="text-[14px] font-semibold text-white mb-4">Activity by Member</h3>
              <div className="space-y-3">
                {users.map((user) => (
                  <div key={user.userId} className="group">
                    <div className="flex items-center justify-between mb-1">
                      <div className="flex items-center gap-2 min-w-0">
                        <div className="w-6 h-6 rounded-full bg-gradient-to-br from-cyan-500/30 to-purple-500/30 flex items-center justify-center text-[10px] font-bold text-white/60 shrink-0">
                          {(user.name || '?')[0]}
                        </div>
                        <span className="text-[13px] text-white/80 font-medium truncate">{user.name}</span>
                      </div>
                      <div className="flex items-center gap-3 shrink-0">
                        <span className="text-[11px] text-white/25">M:{user.avgMouse}%</span>
                        <span className="text-[11px] text-white/25">K:{user.avgKeyboard}%</span>
                        <span className="text-[12px] text-cyan-400 font-semibold">{user.avgOverall}%</span>
                        <span className={`text-[11px] font-medium ${user.idlePercentage > 30 ? 'text-amber-400' : 'text-white/25'}`}>
                          {user.idlePercentage}% idle
                        </span>
                      </div>
                    </div>
                    <div className="h-1.5 bg-white/[0.06] rounded-full overflow-hidden">
                      <div
                        className={`h-full rounded-full transition-all duration-500 ${
                          user.avgOverall >= 75
                            ? 'bg-gradient-to-r from-emerald-500/60 to-emerald-400/40'
                            : user.avgOverall >= 50
                            ? 'bg-gradient-to-r from-cyan-500/60 to-cyan-400/40'
                            : user.avgOverall >= 20
                            ? 'bg-gradient-to-r from-amber-500/60 to-amber-400/40'
                            : 'bg-gradient-to-r from-red-500/60 to-red-400/40'
                        }`}
                        style={{ width: `${user.avgOverall}%` }}
                      />
                    </div>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Daily Activity Trend */}
          {dailyTrend.length > 0 && (
            <div className="bg-white/[0.03] rounded-2xl border border-white/[0.06] p-5">
              <h3 className="text-[14px] font-semibold text-white mb-4">Daily Activity Trend</h3>
              <div className="flex items-end gap-1.5 h-32">
                {dailyTrend.map((day) => {
                  const heightPct = maxDailyAvg > 0 ? (day.avgOverall / maxDailyAvg) * 100 : 0;
                  const color = day.avgOverall >= 60 ? 'bg-emerald-500/50' : day.avgOverall >= 40 ? 'bg-cyan-500/40' : 'bg-amber-500/40';
                  return (
                    <div key={day._id} className="flex-1 flex flex-col items-center gap-1 group min-w-0">
                      <span className="text-[9px] text-white/20 opacity-0 group-hover:opacity-100 transition-opacity">
                        {Math.round(day.avgOverall)}%
                      </span>
                      <div
                        className={`w-full rounded-t-md transition-all duration-300 ${color} hover:opacity-80`}
                        style={{ height: `${Math.max(heightPct, 4)}%` }}
                      />
                      <span className="text-[8px] text-white/15 font-mono truncate w-full text-center">
                        {day._id.slice(5)}
                      </span>
                    </div>
                  );
                })}
              </div>
            </div>
          )}
        </>
      )}
    </div>
  );
};

export default ActivityLevelsTab;
